// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol
// is pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol);
// the snapshot's live-token protocols are kept apart and shown as the market's own values, never
// mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The multiple is not a flat house
// constant: it is the snapshot's own comparable multiple, the median market-cap-to-TVL ratio of the
// live-token protocols in the same category (at least four comparables, else the whole live set's
// median), clamped to [0.05, 1.0]. A Dexs protocol is priced like live Dexs protocols, a lending
// protocol like live lending protocols, and a category with no live comparables falls back to the
// market as a whole. No protocol name is ever special-cased: the same function scores every row.
//
//   multiple   = median(mcap_usd / tvl_usd) over live protocols in the category (>= 4 comps),
//                else the median over all live protocols, clamped to [0.05, 1.0]
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.04 x min(chains - 1, 5)            (more chains, wider distribution)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// The dashboard recomputes every row with the same function, from the same figures, so the page's
// code and board.json agree; its model lab lets a reader change the growth weight and the multiple
// scale and watch the board re-rank live.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

